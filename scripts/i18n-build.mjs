import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const messages = JSON.parse(await readFile(new URL('locales/messages.json', root), 'utf8'));
assert.ok(Object.keys(messages).length > 1000);
const parameters = value => [...value.matchAll(/\{(\d+)\}/g)].map(match => match[1]).sort();
for (const [key, value] of Object.entries(messages)) {
  assert.equal(typeof value, 'string'); assert.ok(value.trim(), key);
  assert.deepEqual(parameters(key), parameters(value), 'Translation parameters changed: ' + key);
}
const generated = '// Generated by scripts/i18n-build.mjs from locales/messages.json.\n' + 'globalThis.sahmLocaleMessages = Object.freeze(' + JSON.stringify(messages) + ');\n';
const target = new URL('browser/extension/i18n-data.js', root);
if (process.argv.includes('--check')) assert.equal(await readFile(target, 'utf8'), generated, 'Run npm run i18n:build');
else await writeFile(target, generated);
console.log(JSON.stringify({ messages: Object.keys(messages).length, generatedCatalogueMatches: true }));
